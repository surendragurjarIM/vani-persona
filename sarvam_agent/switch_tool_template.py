"""VANI live persona switch: a Sarvam code tool (Tools > Add a tool > Upload Python file).

The agent calls tool:update_persona_mode on a user turn that looks like a change in mood, pace,
understanding, interest, availability or language. This file then decides the switch in code
rather than leaving it to the LLM:

* A second detector: the Hinglish lexicon mined from 269k IndiaMART calls (live/lexicon.py) runs
  on the user's words and is fused with the LLM's guess per signal, using the fusion that scored
  best on 2,986 audited turns (frustration F1 0.77, rush 0.67, interest 0.46, confusion 0.43).
* Fixed priority (do-not-call > frustration > rush > unavailable > confusion > interest) and a
  two-turn cooldown per mode, so the agent cannot flap between modes.
* Per-seller sensitivity: sellers called four or more times get a lower frustration threshold.
* A language switch is applied with change_language, not just described in the prompt.
* Every switch is appended to a structured log kept for the whole call.

What a code tool cannot see: the SDK passes no audio, pitch, speaking rate, barge-in or silence
timing to a mid-call tool. The tool sees the user's words (from Saaras STT), the agent's variables
and the call language, so detection is text-based plus the seller's history.

GENERATED by sarvam_agent/build_switch_tool.py from live/lexicon.py. Edit the template, not this file.
"""
