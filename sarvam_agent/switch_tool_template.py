def _word(w: str) -> str:
    if w in LOANWORDS:
        return LOANWORDS[w]
    out, i, n = [], 0, len(w)
    while i < n:
        ch = w[i]
        if ch in _C:
            cons = _C[ch]
            if i + 1 < n and w[i + 1] == "़":
                cons, i = _NUKTA.get(ch, cons), i + 1
            nxt = w[i + 1] if i + 1 < n else ""
            if nxt in _M:
                vowel = "a" if nxt == "ा" and i + 2 >= n else _M[nxt]  # final aa is written "a": ka, diya, aaya
                out.append(cons + vowel)
                i += 2
                continue
            if nxt == "्":
                out.append(cons)
                i += 2
                continue
            after = w[i + 2] if i + 2 < n else ""
            # Schwa deletion: drop the inherent 'a' at word end, and mid-word before a consonant carrying a vowel sign.
            drop = bool(out) and (nxt == "" or (nxt in _C and after in _M))
            out.append(cons if drop else cons + "a")
        elif ch in _V:
            out.append(_V[ch])
        elif ch in "ंँ":
            out.append("n")
        elif ch == "ः":
            out.append("h")
        i += 1
    return "".join(out)


def romanise(text: str) -> str:
    """Devanagari words to the romanised Hinglish the lexicon is written in; other text is left as it is."""
    text = text.replace("-", " ").replace("।", " ")
    return _DEVA.sub(lambda m: _word(m.group(0)), text)


def keyword_scores(text: str) -> tuple[dict, dict]:
    """Lexicon score per signal: several hits combine as 1 - prod(1 - w)."""
    low, scores, hits = romanise(text).lower(), {}, {}
    for sig, pats in _COMPILED.items():
        found = [(m.group(0), w) for rx, w in pats for m in [rx.search(low)] if m]
        if found:
            miss = 1.0
            for _, w in found:
                miss *= 1 - w
            scores[sig], hits[sig] = round(1 - miss, 3), [h for h, _ in found]
    return scores, hits


def script_language(text: str) -> Optional[str]:
    for lang, rng in SCRIPT_LANG.items():
        if re.search(rng, text):
            return lang
    return None


def confirmed_signals(text: str, suspected: str, attempt_number: int) -> tuple[dict, dict]:
    """Signals confirmed by the LLM's guess, the lexicon, or both. Returns {signal: source}, hits."""
    scores, hits = keyword_scores(text)
    out = {}
    if suspected == "do_not_call" or DNC_RE.search(text):
        out["do_not_call"] = "llm+keywords" if suspected == "do_not_call" and DNC_RE.search(text) else (
            "llm" if suspected == "do_not_call" else "keywords")
    for sig, alone in KEYWORD_ALONE.items():
        if sig == "frustration" and attempt_number >= 4:
            alone = 0.6  # fatigued sellers: react to the first hint
        kw = scores.get(sig, 0.0) >= alone
        llm = suspected == sig
        if kw or llm:
            out[sig] = "llm+keywords" if kw and llm else ("llm" if llm else "keywords")
    return out, hits


def _int(v, default=0) -> int:
    try:
        return int(str(v).strip())
    except (TypeError, ValueError):
        return default


class UpdatePersonaMode(SarvamTool):
    """Call on a user turn that shows a change in the user's mood, pace, understanding, interest,
    availability or language, or a request not to be called. Returns the delivery mode for the
    next reply. Never mention this tool or its result to the user."""

    user_words: str = Field(description="The user's last reply, word for word, exactly as heard")
    suspected_signal: Literal["frustration", "rush", "confusion", "interest", "unavailable",
                              "do_not_call", "language", "none"] = Field(
        description="What the user's last reply most likely shows")
    user_language: Optional[SarvamToolLanguageName] = Field(
        default=None, description="The language the user spoke in their last reply")
    turn_number: int = Field(description="Number of this user turn in the call, counting from 1")

    async def run(self, context: SarvamToolContext) -> SarvamToolOutput:
        state = context.internal_variables.get("vani_persona_state") or {
            "mode": "base", "last_turn": {}, "log": []}
        try:
            attempts = _int(context.get_agent_variable("attempt_number"), 1)
        except ValueError:
            attempts = 1
        turn = self.turn_number or (len(state["log"]) + 1)
        found, hits = confirmed_signals(self.user_words, self.suspected_signal, attempts)

        chosen = None
        for sig in PRIORITY:
            if sig not in found:
                continue
            last = state["last_turn"].get(sig)
            if sig != "do_not_call" and last is not None and turn - last <= COOLDOWN_TURNS:
                continue
            chosen = sig
            break

        notes = []
        # Language is its own axis: applied alongside any mood mode. Sarvam's own language switch can run
        # before this tool in the same turn, so the switch is judged against the language this tool last
        # saw (the call's start language at first), not only against the current one.
        # Sarvam's own language tool may already have switched the call when this runs, and the call's metadata
        # follows it, so neither can say what the language was before. The tool remembers the last language it saw;
        # on the first call it learns it from the current language unless that very turn is the switch.
        current = str(context.get_current_language())
        prev = state.get("lang")
        if prev is None and self.suspected_signal != "language":
            prev = state["lang"] = current
        target = self.user_language or script_language(self.user_words)
        if target and str(target) != prev and target in context.allowed_languages:
            if str(target) != current:
                context.change_language(target)
            state["log"].append({"turn": turn, "signal": "language", "evidence": self.user_words[:160],
                                 "source": "llm" if self.user_language else "script",
                                 "from": prev or "call start language", "to": str(target)})
            state["lang"] = str(target)
            notes.append(f"Reply in {target} from now on, same persona.")

        if chosen and chosen != state["mode"]:
            state["log"].append({"turn": turn, "signal": chosen, "evidence": self.user_words[:160],
                                 "source": found[chosen], "keywords": hits.get(chosen, []),
                                 "from": state["mode"], "to": chosen})
            state["mode"], state["last_turn"][chosen] = chosen, turn
            notes.insert(0, f"Mode is now {chosen}. Next reply: {PLAYBOOK[chosen]}")
        elif chosen:
            state["last_turn"][chosen] = turn
            notes.insert(0, f"Stay in {chosen} mode. Next reply: {PLAYBOOK[chosen]}")
        elif not notes:
            keep = PLAYBOOK.get(state["mode"], "Continue the current phase in the seller's persona.")
            notes.append(f"No mode change ({state['mode']}). {keep}")

        context.set_internal_variable("vani_persona_state", state)
        if "live_switch_log" in context.agent_variables:
            context.set_agent_variable("live_switch_log", json.dumps(state["log"], ensure_ascii=False))
        notes.append("Say nothing about this check to the user.")
        return SarvamToolOutput(message_to_llm=" ".join(notes), context=context)
